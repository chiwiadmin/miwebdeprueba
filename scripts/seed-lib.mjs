/*
  Builds db seed SQL from a songs file and validates it.
  Input shape: { startDate: "YYYY-MM-DD", songs: [{ titles: [..], artist: "..", clues: [a, b, c] }] }
  Song N is scheduled on startDate + N days.
*/

import { normalize } from "../public/assets/js/game-core.js";
import { addDays } from "../server/dates.js";

const EXPECTED_DAYS = 30;
const TEST_MARKER = /prueba|\[revisar\]/i;

const quote = (text) => `'${String(text).replace(/'/g, "''")}'`;

export function buildSeed(data, artistList, { allowTest = false, start, expectedDays = EXPECTED_DAYS } = {}) {
  const errors = [];
  const songs = Array.isArray(data && data.songs) ? data.songs : [];
  const startDate = start || (data && data.startDate);
  const artistNames = new Set(artistList.map((a) => a.name));

  if (!/^\d{4}-\d{2}-\d{2}$/.test(startDate || "") || Number.isNaN(Date.parse(startDate))) {
    errors.push(`startDate inválida: ${startDate}`);
  }
  if (!allowTest && songs.length !== expectedDays) {
    errors.push(`Se esperan ${expectedDays} canciones y hay ${songs.length}.`);
  }
  if (!songs.length) errors.push("No hay canciones.");

  const seenTitles = new Map();
  songs.forEach((song, index) => {
    const label = `Canción ${index + 1}`;
    const titles = Array.isArray(song.titles) ? song.titles : [];
    const clues = Array.isArray(song.clues) ? song.clues : [];

    if (!titles.length || titles.some((t) => typeof t !== "string" || !t.trim() || t.length > 100)) {
      errors.push(`${label}: titles debe tener al menos un título válido (máx. 100 caracteres).`);
    }
    if (!artistNames.has(song.artist)) {
      errors.push(`${label}: el artista "${song.artist}" no existe en artists.json (debe coincidir exacto).`);
    }
    if (clues.length !== 3 || clues.some((c) => typeof c !== "string" || !c.trim() || c.length > 200)) {
      errors.push(`${label}: debe tener exactamente 3 frases no vacías (máx. 200 caracteres).`);
    }
    if (!allowTest && [...titles, ...clues].some((t) => TEST_MARKER.test(String(t)))) {
      errors.push(`${label}: tiene texto pendiente ("prueba" o "[REVISAR]"). Corregilo antes de publicar.`);
    }
    for (const title of titles) {
      const key = normalize(title);
      if (seenTitles.has(key) && seenTitles.get(key) !== index) {
        errors.push(`${label}: el título "${title}" ya se usa en la canción ${seenTitles.get(key) + 1}.`);
      }
      seenTitles.set(key, index);
    }
  });

  if (errors.length) return { errors, sql: null };

  const lines = ["-- Generated by scripts/build-seed.mjs. Do not commit: it contains the answers.", "DELETE FROM schedule;", "DELETE FROM songs;"];
  songs.forEach((song, index) => {
    const id = index + 1;
    lines.push(
      `INSERT INTO songs (id, titles, artist, clue1, clue2, clue3) VALUES (${id}, ${quote(JSON.stringify(song.titles))}, ${quote(song.artist)}, ${quote(song.clues[0])}, ${quote(song.clues[1])}, ${quote(song.clues[2])});`
    );
    lines.push(`INSERT INTO schedule (play_date, song_id) VALUES (${quote(addDays(startDate, index))}, ${id});`);
  });
  return { errors: [], sql: lines.join("\n") + "\n" };
}
